#!/usr/bin/env bash
#
# Creates all Azure resources for the Durable Function Order Processing PoC.
#
# Usage:
#   ./infra/provision.sh              # uses defaults
#   ./infra/provision.sh my-suffix    # appends suffix to resource names
#
set -euo pipefail

SUFFIX="${1:-durableevent}"
LOCATION="uksouth"
RESOURCE_GROUP="rg-durable-fn-event-poc"

# Resource names (must be globally unique where required)
STORAGE_ACCOUNT="storderproc${SUFFIX}"
APP_INSIGHTS="ai-order-proc-${SUFFIX}"
LOG_ANALYTICS="la-order-proc-${SUFFIX}"
SERVICEBUS_NAMESPACE="sb-order-proc-${SUFFIX}"
EVENTGRID_TOPIC="egt-order-proc-${SUFFIX}"
FUNCTION_APP="func-order-proc-${SUFFIX}"
DTS_SCHEDULER="dts-order-proc-${SUFFIX}"
DTS_TASKHUB="CreateOrderHub"

# ──────────────────────────────────────────────
# Resources file — written incrementally so values
# are available even if provisioning fails mid-way.
# ──────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RESOURCES_FILE="${SCRIPT_DIR}/resources.env"

write_env() { echo "$1=$2" >>"${RESOURCES_FILE}"; }

cat >"${RESOURCES_FILE}" <<EOF
# Auto-generated by provision.sh — do not edit manually
SUFFIX=${SUFFIX}
LOCATION=${LOCATION}
RESOURCE_GROUP=${RESOURCE_GROUP}
STORAGE_ACCOUNT=${STORAGE_ACCOUNT}
APP_INSIGHTS=${APP_INSIGHTS}
LOG_ANALYTICS=${LOG_ANALYTICS}
SERVICEBUS_NAMESPACE=${SERVICEBUS_NAMESPACE}
EVENTGRID_TOPIC=${EVENTGRID_TOPIC}
FUNCTION_APP=${FUNCTION_APP}
DTS_SCHEDULER=${DTS_SCHEDULER}
DTS_TASKHUB=${DTS_TASKHUB}
EOF

echo "=== Provisioning Azure resources ==="
echo "Resource Group:      ${RESOURCE_GROUP}"
echo "Location:            ${LOCATION}"
echo "Storage Account:     ${STORAGE_ACCOUNT}"
echo "Service Bus:         ${SERVICEBUS_NAMESPACE}"
echo "Event Grid Topic:    ${EVENTGRID_TOPIC}"
echo "DTS Scheduler:       ${DTS_SCHEDULER}"
echo "DTS Task Hub:        ${DTS_TASKHUB}"
echo "Function App:        ${FUNCTION_APP}"
echo ""

# ──────────────────────────────────────────────
# 1. Resource Group
# ──────────────────────────────────────────────
echo "➤ Creating resource group..."
az group create \
  --name "${RESOURCE_GROUP}" \
  --location "${LOCATION}" \
  --output none

# ──────────────────────────────────────────────
# 2. Storage Account (used by Durable Functions + AzureWebJobsStorage)
# ──────────────────────────────────────────────
echo "➤ Creating storage account..."
az storage account create \
  --name "${STORAGE_ACCOUNT}" \
  --resource-group "${RESOURCE_GROUP}" \
  --location "${LOCATION}" \
  --sku Standard_LRS \
  --kind StorageV2 \
  --min-tls-version TLS1_2 \
  --output none

# ──────────────────────────────────────────────
# 3. Log Analytics Workspace (required by Application Insights)
# ──────────────────────────────────────────────
echo "➤ Creating Log Analytics workspace..."
az monitor log-analytics workspace create \
  --resource-group "${RESOURCE_GROUP}" \
  --workspace-name "${LOG_ANALYTICS}" \
  --location "${LOCATION}" \
  --output none

LOG_ANALYTICS_ID=$(az monitor log-analytics workspace show \
  --resource-group "${RESOURCE_GROUP}" \
  --workspace-name "${LOG_ANALYTICS}" \
  --query id \
  --output tsv)
write_env "LOG_ANALYTICS_ID" "${LOG_ANALYTICS_ID}"

# ──────────────────────────────────────────────
# 4. Application Insights
# ──────────────────────────────────────────────
echo "➤ Creating Application Insights..."
az monitor app-insights component create \
  --app "${APP_INSIGHTS}" \
  --resource-group "${RESOURCE_GROUP}" \
  --location "${LOCATION}" \
  --kind web \
  --application-type web \
  --workspace "${LOG_ANALYTICS_ID}" \
  --output none

AI_CONNECTION_STRING=$(az monitor app-insights component show \
  --app "${APP_INSIGHTS}" \
  --resource-group "${RESOURCE_GROUP}" \
  --query connectionString \
  --output tsv)
write_env "AI_CONNECTION_STRING" "${AI_CONNECTION_STRING}"

# ──────────────────────────────────────────────
# 5. Service Bus Namespace + Queues
# ──────────────────────────────────────────────
echo "➤ Creating Service Bus namespace..."
az servicebus namespace create \
  --name "${SERVICEBUS_NAMESPACE}" \
  --resource-group "${RESOURCE_GROUP}" \
  --location "${LOCATION}" \
  --sku Basic \
  --output none

echo "➤ Creating queue: order-created..."
az servicebus queue create \
  --name "order-created" \
  --namespace-name "${SERVICEBUS_NAMESPACE}" \
  --resource-group "${RESOURCE_GROUP}" \
  --max-delivery-count 5 \
  --default-message-time-to-live "P1D" \
  --lock-duration "PT1M" \
  --enable-dead-lettering-on-message-expiration true \
  --output none

echo "➤ Creating queue: payment-captured..."
az servicebus queue create \
  --name "payment-captured" \
  --namespace-name "${SERVICEBUS_NAMESPACE}" \
  --resource-group "${RESOURCE_GROUP}" \
  --max-delivery-count 5 \
  --default-message-time-to-live "P1D" \
  --lock-duration "PT1M" \
  --enable-dead-lettering-on-message-expiration true \
  --output none

SB_CONNECTION_STRING=$(az servicebus namespace authorization-rule keys list \
  --name "RootManageSharedAccessKey" \
  --namespace-name "${SERVICEBUS_NAMESPACE}" \
  --resource-group "${RESOURCE_GROUP}" \
  --query primaryConnectionString \
  --output tsv)
write_env "SB_CONNECTION_STRING" "${SB_CONNECTION_STRING}"

# ──────────────────────────────────────────────
# 6. Event Grid Topic
# ──────────────────────────────────────────────
echo "➤ Creating Event Grid topic..."
az eventgrid topic create \
  --name "${EVENTGRID_TOPIC}" \
  --resource-group "${RESOURCE_GROUP}" \
  --location "${LOCATION}" \
  --input-schema cloudeventschemav1_0 \
  --output none

EG_ENDPOINT=$(az eventgrid topic show \
  --name "${EVENTGRID_TOPIC}" \
  --resource-group "${RESOURCE_GROUP}" \
  --query endpoint \
  --output tsv)
write_env "EG_ENDPOINT" "${EG_ENDPOINT}"

EG_KEY=$(az eventgrid topic key list \
  --name "${EVENTGRID_TOPIC}" \
  --resource-group "${RESOURCE_GROUP}" \
  --query key1 \
  --output tsv)
write_env "EG_KEY" "${EG_KEY}"

# Create a storage queue to receive Event Grid events for inspection
STORAGE_QUEUE="order-completed-events"

echo "➤ Creating storage queue: ${STORAGE_QUEUE}..."
STORAGE_KEY=$(az storage account keys list \
  --account-name "${STORAGE_ACCOUNT}" \
  --resource-group "${RESOURCE_GROUP}" \
  --query '[0].value' \
  --output tsv)

az storage queue create \
  --name "${STORAGE_QUEUE}" \
  --account-name "${STORAGE_ACCOUNT}" \
  --account-key "${STORAGE_KEY}" \
  --output none

STORAGE_ACCOUNT_ID=$(az storage account show \
  --name "${STORAGE_ACCOUNT}" \
  --resource-group "${RESOURCE_GROUP}" \
  --query id \
  --output tsv)

echo "➤ Creating Event Grid subscription → storage queue..."
az eventgrid event-subscription create \
  --name "order-completed-to-queue" \
  --source-resource-id "$(az eventgrid topic show \
    --name "${EVENTGRID_TOPIC}" \
    --resource-group "${RESOURCE_GROUP}" \
    --query id \
    --output tsv)" \
  --endpoint-type storagequeue \
  --endpoint "${STORAGE_ACCOUNT_ID}/queueservices/default/queues/${STORAGE_QUEUE}" \
  --event-delivery-schema cloudeventschemav1_0 \
  --output none

write_env "STORAGE_QUEUE" "${STORAGE_QUEUE}"

# ──────────────────────────────────────────────
# 7. Durable Task Scheduler + Task Hub
# ──────────────────────────────────────────────
echo "➤ Installing durabletask CLI extension..."
az extension add --name durabletask --upgrade --yes 2>/dev/null || true

echo "➤ Creating Durable Task Scheduler..."
az durabletask scheduler create \
  --name "${DTS_SCHEDULER}" \
  --resource-group "${RESOURCE_GROUP}" \
  --location "${LOCATION}" \
  --sku-name "Consumption" \
  --ip-allowlist "[0.0.0.0/0]" \
  --output none

echo "➤ Waiting for Durable Task Scheduler to be ready..."
az durabletask scheduler wait \
  --name "${DTS_SCHEDULER}" \
  --resource-group "${RESOURCE_GROUP}" \
  --created

echo "➤ Creating Task Hub: ${DTS_TASKHUB}..."
az durabletask taskhub create \
  --name "${DTS_TASKHUB}" \
  --resource-group "${RESOURCE_GROUP}" \
  --scheduler-name "${DTS_SCHEDULER}" \
  --output none

DTS_ENDPOINT=$(az durabletask scheduler show \
  --name "${DTS_SCHEDULER}" \
  --resource-group "${RESOURCE_GROUP}" \
  --query endpoint \
  --output tsv)
write_env "DTS_ENDPOINT" "${DTS_ENDPOINT}"

# ──────────────────────────────────────────────
# 8. Function App (Flex Consumption)
# ──────────────────────────────────────────────
echo "➤ Creating Function App (Flex Consumption)..."
az functionapp create \
  --name "${FUNCTION_APP}" \
  --resource-group "${RESOURCE_GROUP}" \
  --storage-account "${STORAGE_ACCOUNT}" \
  --flexconsumption-location "${LOCATION}" \
  --runtime node \
  --runtime-version 24 \
  --functions-version 4 \
  --app-insights "${APP_INSIGHTS}" \
  --output none

echo "➤ Enabling system-assigned managed identity..."
az functionapp identity assign \
  --name "${FUNCTION_APP}" \
  --resource-group "${RESOURCE_GROUP}" \
  --output none

FUNCTION_APP_ID=$(az functionapp show \
  --name "${FUNCTION_APP}" \
  --resource-group "${RESOURCE_GROUP}" \
  --query id \
  --output tsv)
write_env "FUNCTION_APP_ID" "${FUNCTION_APP_ID}"

# ──────────────────────────────────────────────
# 9. Configure App Settings
# ──────────────────────────────────────────────
echo "➤ Configuring app settings..."
az functionapp config appsettings set \
  --name "${FUNCTION_APP}" \
  --resource-group "${RESOURCE_GROUP}" \
  --settings \
  "ServiceBusConnection=${SB_CONNECTION_STRING}" \
  "APPLICATIONINSIGHTS_CONNECTION_STRING=${AI_CONNECTION_STRING}" \
  "EventGridTopicEndpoint=${EG_ENDPOINT}" \
  "EventGridTopicKey=${EG_KEY}" \
  "TASKHUB_NAME=${DTS_TASKHUB}" \
  --output none

# ──────────────────────────────────────────────
# 10. Attach Durable Task Scheduler to Function App
# ──────────────────────────────────────────────
echo "➤ Attaching Durable Task Scheduler to Function App..."

az durabletask scheduler attach \
  --name "${DTS_SCHEDULER}" \
  --resource-group "${RESOURCE_GROUP}" \
  --task-hub-name "${DTS_TASKHUB}" \
  --role-type contributor \
  --target "${FUNCTION_APP_ID}"

echo ""
echo "=== Provisioning complete ==="
echo ""
echo "Resource details written to: ${RESOURCES_FILE}"
echo ""
echo "Function App:        ${FUNCTION_APP}"
echo "Service Bus:         ${SERVICEBUS_NAMESPACE}"
echo "Event Grid Topic:    ${EVENTGRID_TOPIC}"
echo "DTS Scheduler:       ${DTS_SCHEDULER}"
echo "DTS Task Hub:        ${DTS_TASKHUB}"
echo "DTS Endpoint:        ${DTS_ENDPOINT}"
echo "Storage Account:     ${STORAGE_ACCOUNT}"
echo "App Insights:        ${APP_INSIGHTS}"
echo ""
echo "Deploy with:  ./infra/deploy.sh"
